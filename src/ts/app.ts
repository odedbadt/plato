  // Swaps the reflection group under whatever the shape controls currently
  // say, so a stellation or a seed position carries from one symmetry to the
  // next instead of being reset by the change.
  //
  // One triple drives both kernels. Which geometry the numbers describe is
  // settled by the determinant of their Gram matrix, and that decides which
  // generator runs — there is no mode for the user to set, and no way to ask
  // for a tiling in a geometry that cannot hold it.
  set_triple(angles: Angles): boolean {
    const [x, y, z] = angles;
    if (!triple_is_valid(x, y, z)) {
      this.report_triple('each of x, y, z has to be at least 2');
      return false;
    }
    const geometry = classify_triple(x, y, z);
    if (geometry === 'spherical') {
      if (!this.base_spec) return false;
      this.mode = 'spherical';
      this.base_spec = {
        ...this.base_spec, angles,
        family: family_of(angles) ?? this.base_spec.family
      };
    } else {
      // A new group means the old view is a walk through a tiling that no
      // longer exists, so the viewer goes back to the origin.
      if (!same_triple(angles, this.plane_angles) || this.mode !== geometry) {
        this.plane_view = [1, 0, 0, 0, 1, 0, 0, 0, 1];
      }
      this.mode = geometry;
      this.plane_angles = angles;
    }
    this.sync_symmetry_controls();
    this.regenerate_shape();
    return true;
  }

