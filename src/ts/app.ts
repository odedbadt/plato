  async open_model_picker() {
    const overlay = document.getElementById('model-picker-overlay');
    const grid = document.getElementById('model-picker-grid');
    if (!overlay || !grid) return;
    overlay.classList.remove('hidden');

    // Rebuilt on every open: the cards show each symmetry carrying whatever
    // the shape controls currently say, so the grid is a preview of the swap
    // rather than a fixed catalogue.
    grid.innerHTML = '';
    const spec = this.live_spec ?? this.base_spec;
    if (!spec) return;

    // Single shared offscreen renderer reused for every thumbnail.
    const size = 128;
    const thumb_canvas = document.createElement('canvas');
    thumb_canvas.width = size; thumb_canvas.height = size;
    const thumb_tex = document.createElement('canvas');
    thumb_tex.width = 1; thumb_tex.height = 1;
    const thumb_renderer = new WebglRenderer(thumb_canvas, thumb_tex, true);

    const rot = glMatrix.quat.create();
    glMatrix.quat.rotateX(rot, rot, Math.PI / 4);
    glMatrix.quat.rotateY(rot, rot, Math.PI / 5);
    const solid_uniforms = webgl_utils.matrix_uniforms(rot);
    // Thumbnails are square, and a disc reads better than a strip, so the
    // hyperbolic ones all show the disc whichever model the main view is on.
    const disc_uniforms = webgl_utils.orthographic_uniforms(hyperbolic.VIEWPORTS.disc, 1);
    const flat_uniforms = webgl_utils.orthographic_uniforms(euclidean.DEFAULT_VIEWPORT, 1);

    const choices: Angles[] = [
      ...SYMMETRY_FAMILIES.map(f => FAMILY_ANGLES[f]),
      ...EUCLIDEAN_PRESETS,
      ...HYPERBOLIC_PRESETS
    ];

    for (const angles of choices) {
      const [x, y, z] = angles;
      const geometry = classify_triple(x, y, z);
      const seed = spec.seed ? { seed: spec.seed } : {};
      let model, uniforms;
      try {
        if (geometry === 'hyperbolic') {
          // Cheaper than the live view on purpose: a 128px thumbnail cannot
          // show the detail a deeper cutoff would cost it.
          model = hyperbolic.build_hyperbolic({
            x, y, z, cutoff: 0.92, include_mirrors: false, tolerance: 0.006, ...seed
          }).model;
          uniforms = disc_uniforms;
        } else if (geometry === 'euclidean') {
          model = euclidean.build_euclidean({
            x, y, z, scale: 0.3, include_mirrors: false, ...seed
          }).model;
          uniforms = flat_uniforms;
        } else {
          model = generate_model_from_spec(
            { ...spec, angles, family: family_of(angles) ?? spec.family });
          uniforms = solid_uniforms;
        }
      } catch { continue; }

      thumb_renderer.begin_frame();
      thumb_renderer.draw_model(model, uniforms);
      thumb_renderer.end_frame();
      const url = thumb_canvas.toDataURL();

      const label = triple_label(angles);
      const card = document.createElement('div');
      card.className = 'model-thumb-card';
      const img = document.createElement('img');
      img.src = url;
      img.alt = label;
      card.appendChild(img);
      const caption = document.createElement('div');
      caption.className = 'model-thumb-label';
      caption.textContent = label;
      card.appendChild(caption);
      card.addEventListener('click', () => {
        this.set_triple(angles);
        overlay.classList.add('hidden');
      });
      grid.appendChild(card);
    }

    thumb_renderer.renderer.dispose();
  }

